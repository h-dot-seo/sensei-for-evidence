def base():return json.loads((ROOT/'examples/bibliographic-base.json').read_bytes())

def imported(format):
    p=base()
    if format=='CSV':
        artifact=csv.prepare(p,b'record_id,source_locator\nfictional-local,synthetic:local-export\n','local-primary','synthetic supplied time')
        wrapper=None
    else:
        module=nbib if format=='NBIB' else ris
        raw=(b'PMID- 999999999999999999999999999991\nTI  - Fictional only\n' if format=='NBIB' else
             b'TY  - JOUR\nTI  - Fictional only\nID  - fictional-local\nER  -\n')
        wrapper=module.prepare(p,raw,'local-primary','synthetic supplied time')
        module.verify(wrapper)
        artifact=wrapper['csv_intake']
    choices=collection.template(artifact)
    choices['resolutions'][0].update(disposition='new_record',record_id='record-one',rationale='Fictional explicit identity')
    review=collection.prepare_review(p,artifact,choices)['review_document']
    review['review'].update(reviewer='Fictional collection reviewer',reviewed_at='2026-11-14',rationale='Fictional import only',decision='import_for_screening')
    record=collection.assemble(p,artifact,review)
    q=copy.deepcopy(record['protocol_candidate'])
    return p,artifact,record,q,wrapper


def research(format):
    p,a,record,q,wrapper=imported(format)
    q['screening']=[dict(record_id='record-one',decision='include',reason='Fictional inclusion')]
    q['evidence']=[dict(record_id='record-one',evidence_id='result-one',study_id='study-one',locator='synthetic:result',
        model='Fictional model',intervention='Fictional intervention',comparator='Fictional comparator',endpoint='Fictional endpoint',
        result='Fictional supplied result',limitations='Synthetic only',mechanism_basis='unknown')]
    q['synthesis_statements']=[dict(statement_id='statement-one',text='Fictional bounded statement',limitations='Synthetic only',
        evidence_ids=['result-one'],review_status='pending')]
    run(q)
    return p,a,record,q,wrapper


def candidate(p):
    row=challenge.template(p,dict(schema_version=1,statement_ids=['statement-one']))['candidate_document']['challenges'][0]
    row.update(challenge_id='fictional-challenge',challenger='Fictional challenger',challenged_at='2026-11-14',
        alternative_explanation='Fictional alternative, not empirical evidence',missing_discriminating_evidence=[],citation_integrity_findings=[],
        conclusion_width='NOT_ASSESSED',outcome='UNRESOLVED',reopening=None,limitations='Synthetic only',
        independence_declaration='Fictional label; not authenticated')
    return dict(schema_version=1,challenges=[row])


def assertion(p):
    row=readiness.template(p)['candidate_document']['readiness_assertions'][0]
    row.update(assertion_id='fictional-assertion',assessor='Fictional assessor',assessed_at='2026-11-14',
        evidence_sufficiency='INSUFFICIENT',conclusion_readiness='NOT_READY',scope_statement='Fictional scope',
        rationale='Fictional supplied assessment, not generated by tool',limitations='Synthetic only',reopening={'amendment_note':'Fictional follow-up not started'})
    return dict(schema_version=1,readiness_assertions=[row])


def append(module,p,d,decision):
    rv=module.prepare(p,d)['review_document']
    rv.update(receipt_id='fictional-import-'+decision,decision=decision,reviewer='Fictional importer',reviewed_at='2026-11-14',rationale='Record fictional assertions only')
    record=module.assemble(p,d,rv)
    assert module.verify(p,record)['valid']
    return record


def plain(p):
    q=copy.deepcopy(p);q.pop('bibliographic_imports')
    for s in q['searches']:s.pop('bibliographic_provenance')
    # Synthetic comparison inputs: removing provenance changes existing statement bases.
    # Bind the separate plain control's authored challenge to its own current source.
    source=copy.deepcopy(q);source.pop('challenges',None);source.pop('readiness_assertions',None)
    synthesis=run(source)['synthesis']
    for row in q.get('challenges',[]):row['basis_sha256']=challenge_basis(synthesis,row['statement_ids'])
    return q


class BibliographicAssertionContinuationTests(unittest.TestCase):
    def test_exact_two_name_change_and_existing_validator_bytes(self):
        proof=json.loads((ROOT/'tests/bibliographic_assertion_compatibility.json').read_bytes())
        current=prior_bytes('bibliographic_integrity.py')
        self.assertEqual(current.count(b"'evidence_bases', 'question_records'"),1)
        current=current.replace(b"'evidence_bases', 'question_records'",b"'evidence_bases'",1)
        old=b"'report_study_inventory_reviews', 'evidence_bases',"
        new=old+b" 'challenges', 'readiness_assertions',"
        self.assertEqual(current.count(new),1)
        self.assertEqual(hashlib.sha256(current.replace(new,old)).hexdigest(),proof['prior_bibliographic_integrity_sha256'])
        for name,expected in proof['protected_source_sha256'].items():
            if name == 'research_bundle.py':
                # Round48 intentionally tightens verification, not the builder or gate engine.
                import research_bundle
                baseline=json.loads((ROOT/'tests/research_zip_previous_baselines.json').read_bytes())
                self.assertEqual(expected,baseline['previous_module_sha256'])
                self.assertEqual(hashlib.sha256(prior_builder_source(research_bundle).encode()).hexdigest(),baseline['build_function_sha256'])
                self.assertNotEqual(hashlib.sha256((ROOT/name).read_bytes()).hexdigest(),expected)
            elif name == 'evidence_workflow.py':
                self.assertEqual(hashlib.sha256(prior_workflow_bytes()).hexdigest(),expected,name)
            else:
                self.assertEqual(hashlib.sha256((ROOT/name).read_bytes()).hexdigest(),expected,name)

    def test_three_actual_formats_empty_ledgers_are_existing_stages_not_gate_policy(self):
        for format in FORMATS:
            with self.subTest(format=format):
                _,_,_,p,_=imported(format)
                original=copy.deepcopy(p)
                for field in ('challenges','readiness_assertions'):
                    q=dict(p,**{field:[]});r=run(q);control=run(plain(q))
                    self.assertEqual(r['readiness'],control['readiness'])
                    self.assertEqual(r['flow'],run(p)['flow'])
                    self.assertEqual(q['bibliographic_imports'],p['bibliographic_imports'])
                self.assertEqual(p,original)

    def test_three_formats_separate_import_review_replay_and_existing_gate_results(self):
        for format in FORMATS:
            with self.subTest(format=format):
                original,a,collection_record,p,wrapper=research(format)
                source=copy.deepcopy(p)
                c=candidate(p);cr=append(challenge,p,c,'import_challenges');q=cr['protocol_candidate']
                rd=assertion(q);rr=append(readiness,q,rd,'import_readiness_assertions');final=rr['protocol_candidate']
                self.assertEqual(final['bibliographic_imports'],source['bibliographic_imports'])
                for field in ('question','screening','evidence','synthesis_statements','gaps'):
                    self.assertEqual(final[field],source[field])
                self.assertEqual(run(final)['readiness'],run(plain(final))['readiness'])
                self.assertEqual(run(final)['challenge']['stale_challenge_ids'],[])
                self.assertEqual(run(plain(final))['challenge']['stale_challenge_ids'],[])
                self.assertTrue(challenge.verify(p,cr)['valid']);self.assertTrue(readiness.verify(q,rr)['valid'])
                self.assertTrue(csv.verify(a)['valid']);run(collection_record['protocol_candidate'])
                if wrapper:(nbib if format=='NBIB' else ris).verify(wrapper)
                self.assertEqual(p,source)

    def test_existing_shape_unknown_and_immutable_context_checks_still_reject(self):
        for format in FORMATS:
            _,_,_,p,_=research(format)
            for field in ('challenges','readiness_assertions'):
                for bad in (None,{},True,[{}]):
                    with self.subTest(format=format,field=field,bad=bad),self.assertRaises((ValueError,TypeError)):
                        run(dict(p,**{field:bad}))
            for field,value in [('question','changed'),('inclusion_criteria',['changed']),('arbitrary_enrichment',[])]:
                with self.subTest(format=format,field=field),self.assertRaisesRegex(ValueError,'immutable protocol context changed'):
                    run(dict(p,**{field:value}))
            q=copy.deepcopy(p);q['bibliographic_imports']['imports'][0]['review']['rationale']='tampered'
            with self.assertRaises((ValueError,TypeError,KeyError)):run(q)

